-- 1) Storage bucket for inspection photos & signatures (public)
INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES (
   'inspection-images',
   'inspection-images',
   true,
   10485760 -- 10 MB
)
ON CONFLICT (id) DO NOTHING;

-- 2) Storage policies: drop if exists for our bucket
DROP POLICY IF EXISTS "inspection_images_anon_insert" ON storage.objects;
DROP POLICY IF EXISTS "inspection_images_anon_select" ON storage.objects;
DROP POLICY IF EXISTS "inspection_images_anon_update" ON storage.objects;

-- 3) Inspections table: drop if exists and recreate
DROP TABLE IF EXISTS unit_inspections;
CREATE TABLE unit_inspections (
   id              bigint generated by default as identity primary key,
   inspection_date date,
   building        text,
   suite_number    text,
   inspector_name  text,
   inspector_date  date,
   signature_url   text,
   data            jsonb NOT NULL DEFAULT '{}'::jsonb,
    submitted_at    timestamptz NOT NULL default now(),
    pdf_url         text
 );

-- 4) Row Level Security
ALTER TABLE unit_inspections ENABLE ROW LEVEL SECURITY;

CREATE POLICY "unit_inspections_anon_insert"
   ON unit_inspections
   FOR INSERT
   TO anon
   WITH CHECK (true);

CREATE POLICY "unit_inspections_anon_select"
   ON unit_inspections
   FOR SELECT
   TO anon
   USING (true);

-- 5) Storage RLS so the anon key can upload + read
CREATE POLICY "inspection_images_anon_insert"
   ON storage.objects
   FOR INSERT
   TO anon
   WITH CHECK (bucket_id = 'inspection-images');

CREATE POLICY "inspection_images_anon_select"
   ON storage.objects
   FOR SELECT
   TO anon
   USING (bucket_id = 'inspection-images');

CREATE POLICY "inspection_images_anon_update"
   ON storage.objects
   FOR UPDATE
   TO anon
   USING (bucket_id = 'inspection-images')
   WITH CHECK (bucket_id = 'inspection-images');

-- 5.1) Add PDF URL column (idempotent)
ALTER TABLE unit_inspections ADD COLUMN IF NOT EXISTS pdf_url text;

-- 5.2) Draft / update tracking columns (idempotent)
ALTER TABLE unit_inspections ADD COLUMN IF NOT EXISTS status text DEFAULT 'draft' CHECK (status IN ('draft','in_progress','completed'));
ALTER TABLE unit_inspections ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();
ALTER TABLE unit_inspections ADD COLUMN IF NOT EXISTS updated_by text;
ALTER TABLE unit_inspections ADD COLUMN IF NOT EXISTS update_reason text;
ALTER TABLE unit_inspections ADD COLUMN IF NOT EXISTS update_history jsonb DEFAULT '[]'::jsonb;

-- 4.1) RLS update policy for drafts / updates (anon)
DROP POLICY IF EXISTS "unit_inspections_anon_update" ON unit_inspections;
CREATE POLICY "unit_inspections_anon_update"
   ON unit_inspections
   FOR UPDATE
   TO anon
   USING (true)
   WITH CHECK (true);

-- Auto-update updated_at on row update
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_unit_inspections_updated_at ON unit_inspections;
CREATE TRIGGER trg_unit_inspections_updated_at
BEFORE UPDATE ON unit_inspections
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE INDEX IF NOT EXISTS idx_unit_inspections_submitted_at
   ON unit_inspections (submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_unit_inspections_suite
   ON unit_inspections (suite_number);
CREATE INDEX IF NOT EXISTS idx_unit_inspections_status
   ON unit_inspections (status);
CREATE INDEX IF NOT EXISTS idx_unit_inspections_building_suite
   ON unit_inspections (building, suite_number);